-- Task 14: Consume Stream Data

MERGE INTO STREAMS_DB.PUBLIC.SALES_FINAL_TABLE AS T 
USING (
    SELECT 
        SS.ID ,
        SS.PRODUCT, 
        SS.PRICE ,
        SS.AMOUNT , 
        SS.STORE_ID ,
        ST.LOCATION , 
        ST.EMPLOYEES
        FROM STREAMS_DB.PUBLIC.SALES_STREAM AS SS
        INNER JOIN STREAMS_DB.PUBLIC.STORE_TABLE AS ST
        ON SS.STORE_ID = ST.STORE_ID
) AS S
ON T.ID = S.ID 

WHEN MATCHED THEN UPDATE SET 
    T.PRODUCT = S.PRODUCT, 
    T.PRICE  = S.PRICE,
    T.AMOUNT = S.AMOUNT ,
    T.STORE_ID = S.STORE_ID,
    T.LOCATION = S.LOCATION,
    T.EMPLOYEES = S.EMPLOYEES

WHEN NOT MATCHED THEN INSERT
(
    ID,
    PRODUCT, 
    PRICE,
    AMOUNT ,
    STORE_ID,
    LOCATION,
    EMPLOYEES
)
VALUES(
    S.ID,
    S.PRODUCT, 
    S.PRICE,
    S.AMOUNT ,
    S.STORE_ID,
    S.LOCATION,
    S.EMPLOYEES
);



