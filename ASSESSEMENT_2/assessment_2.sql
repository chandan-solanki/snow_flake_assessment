USING (
  SELECT 
        SS.ID ,
        SS.PRODUCT, 
        SS.PRICE ,
        SS.AMOUNT , 
        SS.STORE_ID ,
        ST.LOCATION , 
        ST.EMPLOYEES ,
        SS.METADATA$ACTION , 
        SS.METADATA$ISUPDATE 
        FROM STREAMS_DB.PUBLIC.SALES_STREAM AS SS
        INNER JOIN STREAMS_DB.PUBLIC.STORE_TABLE AS ST
        ON SS.STORE_ID = ST.STORE_ID
) AS S
ON T.ID = S.ID 

WHEN MATCHED 
AND S.METADATA$ACTION = 'INSERT' 
AND S.METADATA$ISUPDATE = TRUE
THEN UPDATE SET 
    T.PRODUCT = S.PRODUCT, 
    T.PRICE  = S.PRICE,
    T.AMOUNT = S.AMOUNT ,
    T.STORE_ID = S.STORE_ID;

